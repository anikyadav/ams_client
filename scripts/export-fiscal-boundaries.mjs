// Regenerate the backend AD allowlist whenever the frontend converter is updated.
// Usage: node scripts/export-fiscal-boundaries.mjs <backend/src/fiscal-years/fiscal-year-boundaries.ts>
import fs from 'node:fs';
import converter from 'nepali-date-converter';
const NepaliDate = converter.default ?? converter;
const dates = [];
for (let year = 2000; year <= 2090; year++) {
  const ad = new NepaliDate(year, 3, 1).getAD();
  dates.push(`${ad.year}-${String(ad.month + 1).padStart(2, '0')}-${String(ad.date).padStart(2, '0')}`);
}
if (!process.argv[2]) throw new Error('Provide the destination TypeScript file');
fs.writeFileSync(process.argv[2], '// Generated by frontend scripts/export-fiscal-boundaries.mjs using nepali-date-converter 3.4.0.\n// AD-only boundaries; BS conversion remains in the frontend. End dates are exclusive.\nexport const fiscalBoundaries = ' + JSON.stringify(dates, null, 2) + ' as const;\n');
